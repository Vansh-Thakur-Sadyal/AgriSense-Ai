"""Re-generate the self-hosted fonts in app/static/fonts.

Scans app/static for every Material Symbols icon name the UI uses, downloads a subset of the icon
font with just those glyphs (plus Inter and Noto Sans Devanagari), rewrites fonts.css to local URLs
and removes font files that are no longer referenced. Run after adding a new icon to the UI:

    python tools/update_fonts.py
"""
import hashlib
import re
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "app" / "static"
FONTS = STATIC / "fonts"
UA = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36"}
CODEPOINTS = ("https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/"
              "MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints")


def main():
    valid = {l.split()[0] for l in httpx.get(CODEPOINTS, timeout=60, follow_redirects=True).text.splitlines() if l.strip()}
    src = "".join(p.read_text(encoding="utf-8") for p in (STATIC / "app.js", STATIC / "index.html", STATIC / "i18n.js"))
    names = set(re.findall(r'["\'`]([a-z][a-z0-9_]{2,40})["\'`]', src)) | set(re.findall(r">([a-z][a-z0-9_]{2,40})</span>", src))
    icons = sorted(names & valid)
    urls = ["https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,400,0,0"
            "&icon_names=" + ",".join(icons) + "&display=block",
            "https://fonts.googleapis.com/css2?family=Inter:wght@400..700&family=Noto+Sans+Devanagari:wght@400;600&display=swap"]
    FONTS.mkdir(parents=True, exist_ok=True)
    keep, parts = set(), []
    for u in urls:
        css = httpx.get(u, headers=UA, timeout=60).text
        assert "@font-face" in css, css[:300]

        def local(m):
            url = m.group(1)
            name = hashlib.sha1(url.encode()).hexdigest()[:12] + ".woff2"
            if not (FONTS / name).exists():
                (FONTS / name).write_bytes(httpx.get(url, headers=UA, timeout=60).content)
            keep.add(name)
            return f"url(/fonts/{name})"
        parts.append(re.sub(r"url\((https://fonts\.gstatic\.com/[^)]+)\)", local, css))
    (FONTS / "fonts.css").write_text("/* Self-hosted copies of Google Fonts (Material Symbols subset of the icons this app uses, Inter, "
                                     "Noto Sans Devanagari). Generated by tools/update_fonts.py; do not edit. */\n" + "\n".join(parts),
                                     encoding="utf-8")
    stale = [p for p in FONTS.glob("*.woff2") if p.name not in keep]
    for p in stale:
        p.unlink()
    print(f"{len(icons)} icons; {len(keep)} font files kept, {len(stale)} stale removed")


if __name__ == "__main__":
    main()
